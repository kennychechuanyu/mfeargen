test_that("prior constructors reject invalid values", {
  expect_error(prior_normal(sd = NA_real_), "finite")
  expect_error(prior_gamma(shape = 2, scale = -1), "positive")
  expect_error(prior_beta(shape1 = c(1, 2), shape2 = 2), "finite")
  expect_error(prior_uniform(1, Inf), "finite")
  expect_error(prior_lognormal(mean = 1), "both")
  expect_error(prior_lognormal(meanlog = 0, sdlog = 1, mean = 2, sd = 1), "either")
  expect_error(prior_dirichlet(c(1, NA_real_)), "finite")
  expect_error(prior_normal(truncate = c(2, 1)), "increasing")
  expect_error(set_priors(unknown = prior_normal()), "Unknown prior")
  expect_error(set_priors_flexible(alpha_mu = prior_normal()), "requires")
  expect_error(set_priors(pi_alpha = c(1, 1)), "four")
  expect_error(set_priors(sigma1_min = -1), "non-negative")
})

test_that("prior parameterizations preserve their intended distributions", {
  beta <- prior_beta(mode = 0.7, concentration = 10)
  expect_equal((beta$a - 1) / (beta$a + beta$b - 2), 0.7)
  lognormal <- prior_lognormal(mean = 2, sd = 1)
  expect_equal(exp(lognormal$mean + lognormal$sdlog^2 / 2), 2)
  expect_equal((exp(lognormal$sdlog^2) - 1) * exp(2 * lognormal$mean + lognormal$sdlog^2), 1)
  syntax <- prior_to_jags(prior_normal(sd = 1000), "x")
  precision <- as.numeric(sub("^.*,[[:space:]]*([^,]*)\\)$", "\\1", syntax))
  expect_equal(precision, 1e-6)
  expect_match(prior_to_jags(prior_half_cauchy(2), "x"), "dt(0, 2.5e-01, 1) T(0e+00,)", fixed = TRUE)
  expect_match(prior_to_jags(prior_student_t(3), "x"), "dt(", fixed = TRUE)
})

test_that("combining priors retains template values and explicit overrides", {
  template <- get_strong_priors(expected_lambda = 0.2)
  combined <- combine_priors(template, set_priors_flexible(alpha_mu = prior_beta(3, 7)))
  expect_equal(combined$lambda_mu, template$lambda_mu)
  expect_equal(combined$alpha_mu$a, 3)
  expect_equal(combined$alpha_mu, combined$alpha)
  combined <- combine_priors(template, set_priors(lambda_mu_mean = -3, sigma2_max = 5))
  expect_equal(combined$lambda_mu$mean, -3)
  expect_equal(combined$sigma2$max, 5)
  expect_equal(combined$sigma1, template$sigma1)
  expect_equal(combined$sigma, combined$sigma1)
})
